// Draws the app icon (an open book) as a 512x512 PNG and writes src/icon.ts.
import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";

const S = 512;
const bg = [0x1f, 0x3a, 0x5f], page = [0xf7, 0xf3, 0xe8], line = [0xc9, 0xbf, 0xa8], spine = [0xe0, 0x8e, 0x45];
const px = new Uint8Array(S * S * 3);
const set = (x, y, c) => { const i = (y * S + x) * 3; px[i] = c[0]; px[i + 1] = c[1]; px[i + 2] = c[2]; };
for (let y = 0; y < S; y++) for (let x = 0; x < S; x++) {
  let c = bg;
  const cx = x - 256;
  const sag = Math.round((Math.abs(cx) / 150) ** 2 * -18); // pages curve up at the outer edge
  const top = 150 + sag, bottom = 370 + sag + 0;
  if (Math.abs(cx) >= 8 && Math.abs(cx) <= 170 && y >= top && y <= bottom) {
    c = page;
    const rel = y - top;
    if (Math.abs(cx) >= 35 && Math.abs(cx) <= 145 && rel > 35 && rel < 200 && rel % 32 < 6) c = line;
  }
  if (Math.abs(cx) < 8 && y >= 140 && y <= 385) c = spine;
  set(x, y, c);
}
const raw = Buffer.alloc((S * 3 + 1) * S);
for (let y = 0; y < S; y++) { raw[y * (S * 3 + 1)] = 0; Buffer.from(px.buffer, y * S * 3, S * 3).copy(raw, y * (S * 3 + 1) + 1); }
const crcT = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (b) => { let c = 0xffffffff; for (const v of b) c = crcT[(c ^ v) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(S, 0); ihdr.writeUInt32BE(S, 4); ihdr[8] = 8; ihdr[9] = 2;
const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
writeFileSync(new URL("../src/icon.ts", import.meta.url), `// Generated by scripts/make-icon.mjs. Do not edit.\nexport const APPLE_TOUCH_ICON_PNG_BASE64 =\n  "${png.toString("base64")}";\n`);
console.log("icon bytes:", png.length);
